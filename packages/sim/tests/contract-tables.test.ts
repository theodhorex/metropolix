// The contract's rule tables (contracts/metropolix/src/tables.rs) are generated from this package, so the
// chain and the game never drift apart again. `UPDATE=1 pnpm test` rewrites the file; the test fails if it is stale.
import { it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';
import * as sim from '../src';

const OUT = path.resolve(__dirname, '../../../contracts/metropolix/src/tables.rs');

function render(): string {
  const B = sim.BUILDING_KINDS.map((k) => sim.BUILDINGS[k]);
  const arcIdx = (id: sim.ArcId | undefined) => (id ? sim.ARCS.findIndex((a) => a.id === id) : 255);
  const arr = (name: string, ty: string, vals: (number | string)[]) => `pub const ${name}: [${ty}; ${vals.length}] = [${vals.join(', ')}];`;
  const strs = (name: string, vals: string[]) => `pub const ${name}: [&str; ${vals.length}] = [${vals.map((v) => JSON.stringify(v)).join(', ')}];`;
  const lines = [
    '// GENERATED by packages/sim/tests/contract-tables.test.ts from @metropolix/sim. Do not edit by hand:',
    '// change the sim, then run `UPDATE=1 pnpm --filter @metropolix/sim test`.',
    '#![allow(dead_code)]',
    '',
    '/// Building codes: 0 = empty, code i = BUILDING_KINDS[i - 1].',
    `pub const BUILDING_COUNT: usize = ${B.length};`,
    strs('BUILDING_KINDS', [...sim.BUILDING_KINDS]),
    arr('COST', 'u64', B.map((b) => b.cost)),
    arr('HOUSING', 'u64', B.map((b) => b.housing ?? 0)),
    arr('JOBS', 'u64', B.map((b) => b.jobs ?? 0)),
    arr('OUTPUT', 'u64', B.map((b) => b.output ?? 0)),
    arr('UPKEEP', 'u64', B.map((b) => b.upkeep ?? 0)),
    arr('TROOP_CAP', 'u64', B.map((b) => b.troopCap ?? 0)),
    arr('DEFENSE', 'u64', B.map((b) => b.defense ?? 0)),
    arr('ATK_PM', 'u64', B.map((b) => b.atkPm ?? 0)),
    '/// The people that alone may build this wonder (index into ARC_IDS), 255 = anyone.',
    arr('WONDER_ARC', 'u8', B.map((b) => arcIdx(b.arc))),
    '/// Most of this kind one city may own, 0 = no limit.',
    arr('LIMIT', 'u64', B.map((b) => b.limit ?? 0)),
    arr('CAN_UPGRADE', 'bool', sim.BUILDING_KINDS.map((k) => String(sim.canUpgrade(k)))),
    '',
    strs('ARC_IDS', sim.ARCS.map((a) => a.id)),
    arr('ARC_ATTACK_PM', 'u64', sim.ARCS.map((a) => a.mods.attackPm)),
    arr('ARC_DEFENSE_PM', 'u64', sim.ARCS.map((a) => a.mods.defensePm)),
    arr('ARC_ECON_PM', 'u64', sim.ARCS.map((a) => a.mods.econPm)),
    arr('ARC_LOOT_PM', 'u64', sim.ARCS.map((a) => a.mods.lootPm)),
    '',
    arr('LEVEL_PM', 'u64', [...sim.LEVEL_PM]),
    arr('LEVEL_XP', 'u64', [...sim.LEVEL_XP]),
    `pub const MAX_BLD_LEVEL: u8 = ${sim.MAX_BLD_LEVEL};`,
    `pub const DRILL_PM: u64 = ${sim.DRILL_PM};`,
    `pub const DRILL_CAP_PM: u64 = ${sim.DRILL_CAP_PM};`,
    `pub const BUILD_ATK_CAP_PM: u64 = ${sim.BUILD_ATK_CAP_PM};`,
    `pub const TROOP_ATTACK: u64 = ${sim.TROOP_ATTACK};`,
    `pub const TROOP_DEFENSE: u64 = ${sim.TROOP_DEFENSE};`,
    `pub const BASE_WAGE: u64 = ${sim.BASE_WAGE};`,
    `pub const MAX_TAX: u64 = 30;`,
    `pub const MAX_LOOT_PCT: u64 = ${sim.MAX_LOOT_PCT};`,
    `pub const SHIELD_SECS: u64 = ${sim.SHIELD_TICKS};`,
    `pub const ATTACK_COOLDOWN_SECS: u64 = ${sim.ATTACK_COOLDOWN};`,
    '',
    '/// War Room roles in order vanguard, raider, breaker (permille).',
    arr('ROLE_ATK_PM', 'u64', sim.ROLES.map((r) => sim.ROLE_DEFS[r].atkPm)),
    arr('ROLE_LOSS_PM', 'u64', sim.ROLES.map((r) => sim.ROLE_DEFS[r].lossPm)),
    arr('ROLE_LOOT_PM', 'u64', sim.ROLES.map((r) => sim.ROLE_DEFS[r].lootPm)),
    '',
    strs('RELIC_KINDS', [...sim.RELIC_KINDS]),
    strs('RELIC_NAMES', sim.RELIC_KINDS.map((k) => sim.RELICS[k].name)),
    strs('RELIC_RARITY', sim.RELIC_KINDS.map((k) => sim.RELICS[k].rarity)),
    strs('RELIC_DESC', sim.RELIC_KINDS.map((k) => sim.RELICS[k].desc)),
    '',
  ];
  return lines.join('\n');
}

it('contract tables match the sim', () => {
  const want = render();
  if (process.env.UPDATE) fs.writeFileSync(OUT, want);
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  expect(have, 'contract tables are stale: run UPDATE=1 pnpm --filter @metropolix/sim test').toBe(want);
});
